export const getEmojisByCategory = (category: EmojiCategory): Emoji[] => {
  return emojis.filter(emoji => emoji.category === category);
};

export const searchEmojis = (query: string): Emoji[] => {
  if (!query.trim()) return emojis;
  
  const lowercaseQuery = query.toLowerCase();
  
  return emojis.filter(emoji => 
    emoji.name.toLowerCase().includes(lowercaseQuery) ||
    emoji.keywords.some(keyword => keyword.toLowerCase().includes(lowercaseQuery)) ||
    emoji.category.toLowerCase().includes(lowercaseQuery)
  );
};